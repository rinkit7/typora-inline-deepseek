import {build} from "esbuild";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import {fileURLToPath} from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const output = path.join(root,"dist");
fs.mkdirSync(output,{recursive:true});
const result = await build({entryPoints:[path.join(root,"ui/chat-ui.jsx")],outfile:path.join(output,"chat-ui.js"),bundle:true,format:"esm",platform:"browser",target:"chrome110",minify:true,metafile:true,legalComments:"external",loader:{".css":"text"},define:{"process.env.NODE_ENV":'"production"'}});
fs.mkdirSync(path.join(output,"fonts"),{recursive:true});
for (const name of fs.readdirSync(path.join(root,"node_modules/katex/dist/fonts"))) fs.copyFileSync(path.join(root,"node_modules/katex/dist/fonts",name),path.join(output,"fonts",name));
const packages = new Map();
for (const file of Object.keys(result.metafile.inputs)) {
  if (!file.includes("node_modules")) continue;
  let directory = path.dirname(path.resolve(file));
  while (directory.startsWith(path.join(root,"node_modules"))) {
    const metadata = path.join(directory,"package.json");
    if (fs.existsSync(metadata)) {const pkg = JSON.parse(fs.readFileSync(metadata,"utf8")); if (pkg.name) packages.set(directory,pkg); break;}
    directory = path.dirname(directory);
  }
}
let notices = "Bundled third-party licenses. Generated by scripts/build.mjs.\n";
for (const [directory,pkg] of [...packages].sort((a,b) => a[1].name.localeCompare(b[1].name))) {
  const name = fs.readdirSync(directory).find(file => /^(license|licence|copying)(\.|$)/i.test(file));
  notices += `\n\n===== ${pkg.name}@${pkg.version} (${pkg.license || "see license"}) =====\n`;
  const overrides = {"react-remove-scroll-bar":"react-remove-scroll-bar.txt","remark-math":"remark-math.txt","rehype-katex":"remark-math.txt"};
  const vendor = overrides[pkg.name] && path.join(root,"vendor-licenses",overrides[pkg.name]);
  if (name) notices += fs.readFileSync(path.join(directory,name),"utf8");
  else if (vendor && fs.existsSync(vendor)) notices += fs.readFileSync(vendor,"utf8");
  else {
    notices += `No separate license file published. Package metadata: ${JSON.stringify({author:pkg.author,license:pkg.license,repository:pkg.repository})}\n`;
    if (pkg.license === "MIT") notices += "Standard MIT terms (based on declared package license):\n" + fs.readFileSync(path.join(root,"LICENSE"),"utf8").replace(/^Copyright.*\r?\n/m,"");
  }
}
fs.writeFileSync(path.join(output,"THIRD-PARTY-LICENSES.txt"),notices);
const uiSourceHash = crypto.createHash("sha256").update(fs.readFileSync(path.join(root,"ui/chat-ui.jsx"))).update(fs.readFileSync(path.join(root,"ui/chat-ui.css"))).update(fs.readFileSync(path.join(root,"src/pointer-gestures.js"))).update(fs.readFileSync(path.join(root,"src/quick-asks.js"))).digest("hex");
fs.writeFileSync(path.join(output,"build-info.json"),JSON.stringify({ui:"assistant-ui",sourceSha256:uiSourceHash,packages:[...packages.values()].map(({name,version}) => ({name,version})),sha256:crypto.createHash("sha256").update(fs.readFileSync(path.join(output,"chat-ui.js"))).digest("hex")},null,2));
console.log(`Built assistant-ui: ${fs.statSync(path.join(output,"chat-ui.js")).size} bytes, ${packages.size} bundled packages.`);
